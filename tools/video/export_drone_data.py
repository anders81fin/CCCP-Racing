#!/usr/bin/env python3
"""Export the approved Kolkhoz drone film's camera data into src/Race/DroneTourData.cs, so the game can fly
it as the first track's tour (CHOOSE TRACK, T) without any files: the baked path every 0.5 s (the game
interpolates it back to 60 Hz), the chase drone's keys, and the marks/timings the staging needs.

  export_drone_data.py NAME PATH.csv LAPKEYS.txt MARKS.json --lap-at S      (NAME: Kolkhoz | Siberia | Atomgrad | Bonus)
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEXTS = Path(__file__).resolve().parent / 'drone_texts.json'
TEXTS_ALL = json.loads(TEXTS.read_text())
STEP = 30  # path rows (60 Hz) between samples = 0.5 s


def rows(path):
    out = []
    for line in Path(path).read_text().splitlines():
        if line.strip() and line[0] != '#':
            out.append([float(x) for x in line.split()])
    return out


def fmt(row, nd):
    return 'new[] { ' + ', '.join(f'{v:.{nd}f}f' for v in row) + ' }'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('name')
    ap.add_argument('path')
    ap.add_argument('keys')
    ap.add_argument('marks')
    ap.add_argument('--lap-at', type=float, required=True)
    a = ap.parse_args()
    path = rows(a.path)
    # Whole SampleStep intervals only: the game maps sample k to k x SampleStep s, so a shorter last interval would slow the end.
    samples = path[:((len(path) - 1) // STEP) * STEP + 1:STEP]
    keys = rows(a.keys)
    marks = json.loads(Path(a.marks).read_text())['marks']
    out = ROOT / f'src/Race/DroneTourData.{a.name}.cs'
    lines = [
        f'// GENERATED by tools/video/export_drone_data.py from the authored {a.name} drone tour. Do not edit.',
        'using System.Collections.Generic;',
        '',
        'namespace CCCPRacing.Race;',
        '',
        'static partial class DroneTourData',
        '{',
        f'    /// <summary>The {a.name} film: the baked flight path, the lap chase keys and the marks (see DroneFilm).</summary>',
        f'    public static class {a.name}',
        '    {',
        f'        public const float LapAt = {a.lap_at:.2f}f;',
        f"        public const float CardEnd = {TEXTS_ALL[a.name.lower()].get('card_hold', 4.5)}f, FilmDelay = {TEXTS_ALL[a.name.lower()].get('film_delay', 0.0)}f;",
        f'        public const float SampleStep = {STEP / 60:.4f}f;',
        '        public static readonly Dictionary<string, float> Marks = new()',
        '        {',
    ]
    for k, v in marks.items():
        lines.append(f'            ["{k}"] = {v:.2f}f,')
    texts = json.loads(TEXTS.read_text())[a.name.lower()]
    q = lambda t: '"' + t.replace('\\', '\\\\').replace('"', '\\"') + '"'
    lines += ['        };',
              '        public static readonly string[] CardBig = { ' + ', '.join(q(t) for t in texts['card_big']) + ' };',
              '        public static readonly string[] CardSmall =', '        {']
    lines += ['            ' + q(t) + ',' for t in texts['card_small']]
    lines += ['        };',
              '        /// <summary>(waypoint mark, seconds after it, seconds shown, text).</summary>',
              '        public static readonly (string mark, float after, float length, string text)[] Captions =', '        {']
    lines += [f'            ({q(c[0])}, {c[1]}f, {c[2]}f, {q(c[3])}),' for c in texts['captions']]
    lines += ['        };',
              '        /// <summary>(from road metre, to road metre, text): shown while the car drives the lap.</summary>',
              '        public static readonly (int from, int to, string text)[] LapCaptions =', '        {']
    lines += [f'            ({c[0]}, {c[1]}, {q(c[2])}),' for c in texts.get('lap_captions', [])]
    lines += ['        };',
              '        /// <summary>eyeX eyeZ eyeAGL targetX targetZ targetAGL fov lightClock, each SampleStep seconds.</summary>',
              '        public static readonly float[][] Path =', '        {']
    for r in samples:
        lines.append('            ' + fmt(r[:8], 2) + ',')
    lines += ['        };', '        /// <summary>By road metre: metre azimuth dist height fov subjectX subjectZ blend.</summary>',
              '        public static readonly float[][] LapKeys =', '        {']
    for r in keys:
        lines.append('            ' + fmt(r, 2) + ',')
    lines += ['        };', '    }', '}', '']
    out.write_text('\n'.join(lines))
    print(f'{out}: {len(samples)} path samples, {len(keys)} lap keys, {out.stat().st_size/1000:.0f} kB')


if __name__ == '__main__':
    main()
