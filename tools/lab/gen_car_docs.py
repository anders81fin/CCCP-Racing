#!/usr/bin/env python3
"""Writes src/Lab/CarParamDocs.cs from the [Export] properties of src/Car/CarParams.cs:
group, name, kind and the doc comment of every float / Vector3 parameter, in source order.
Run it after CarParams.cs changes; the lab-tests fail when the table and the class disagree."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "src/Car/CarParams.cs").read_text().splitlines()
group, doc, out = "Body", [], []
for line in src:
    s = line.strip()
    m = re.match(r'\[ExportGroup\("([^"]+)"\)\]', s)
    if m:
        group = m.group(1); doc = []; continue
    if s.startswith("///"):
        doc.append(re.sub(r"</?[a-zA-Z]+[^>]*>", "", s[3:]).strip()); continue
    if s.startswith("//"):
        doc.append(s[2:].strip()); continue
    m = re.match(r"\[Export\] public (float|Vector3) (\w+)", s)
    if m:
        text = " ".join(d for d in doc if d)
        text = re.sub(r"\s+", " ", text).replace("\\", "\\\\").replace('"', '\\"')
        out.append((group, m.group(2), m.group(1), text))
        doc = []; continue
    if s.startswith("[Export]"):      # a parameter the lab does not handle (the gears)
        doc = []; continue
    if s and not s.startswith("["):
        doc = []

lines = ["// <auto-generated by tools/lab/gen_car_docs.py from src/Car/CarParams.cs: do not edit by hand />",
         "namespace CCCPRacing.Lab;", "",
         "public static class CarParamDocs", "{",
         "    /// <summary>Group, property, kind (float or Vector3) and the description, in the order of CarParams.</summary>",
         "    public static readonly (string Group, string Name, string Kind, string Doc)[] Entries =", "    {"]
for g, n, k, d in out:
    lines.append(f'        ("{g}", "{n}", "{k}", "{d}"),')
lines += ["    };", "}", ""]
(root / "src/Lab/CarParamDocs.cs").write_text("\n".join(lines))
print(len(out), "parameters", file=sys.stderr)
